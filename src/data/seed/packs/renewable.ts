/**
 * PACK A — Renewable energy.
 *
 * Verdanta Group: a vertically integrated renewables business running
 * utility-scale development (Verdanta Terra), residential solar and storage
 * (Sunhaven) and grid-scale batteries (Corevolt) under one corporate parent.
 *
 * Why this vertical: energy claims are genuinely regulated, site and customer
 * footage carries genuinely awkward rights, and a battery safety incident is a
 * genuinely plausible crisis. Those three make the legal library, the graph
 * and the crisis flow do real work rather than decorate a screen.
 *
 * ---------------------------------------------------------------------------
 * RULES THIS FILE HOLDS ITSELF TO
 * ---------------------------------------------------------------------------
 *
 * 1. **Same shapes, same states as the default pack.** Every record is an
 *    unmodified type from `../../types`, every id uses the same prefix scheme,
 *    and the state coverage checklist in `docs/DEMO_PACKS.md` §4 is met
 *    item for item. A bug found in one pack is findable in all of them.
 *
 * 2. **Dates are offsets, never literals.** `d()` / `at()` below resolve
 *    against `PACK_ANCHOR`, which is the app's demo clock. Nothing in this
 *    file reads the wall clock, so the data is deterministic in CI and in the
 *    browser, and moving the anchor moves the whole world with it.
 *
 * 3. **Fictional brands, real regulators.** Verdanta, Verdanta Terra,
 *    Sunhaven and Corevolt are invented. The CMA, the EU Green Claims
 *    Directive, the Saudi SLC local-content regime and UL 9540A are real, and
 *    are named because that is what makes the governance content credible. No
 *    real company or product name appears anywhere in this pack.
 *
 * 4. **Market sizing is flagged, not asserted.** Every `MarketSizing` row
 *    carries the illustrative-placeholder caveat in its own `sourceLabel` and
 *    first assumption, so the caveat travels with the number onto the screen
 *    instead of living in a document nobody opens.
 *
 * 5. **Graph density.** Every asset except two deliberate exceptions is
 *    embedded in at least two content versions, and every content version is
 *    carried by at least one channel execution — so asset → version →
 *    execution → communication → activity → campaign is a real path for
 *    almost every record, not a lucky one.
 *
 *    The two exceptions are stated rather than hidden: `AST-016` is
 *    `Uploaded` and `AST-017` is `Rejected`. Referencing either from live
 *    content would make its status a lie, and an honest hole beats a
 *    convenient link.
 *
 * ---------------------------------------------------------------------------
 * WIRING
 * ---------------------------------------------------------------------------
 * This module exports collections and one assembled `renewablePack: SeedDB`.
 * It does NOT register itself — `src/data/seed/index.ts` owns pack selection.
 * See `docs/DEMO_PACKS.md` §3 for the exact change that file needs.
 */

