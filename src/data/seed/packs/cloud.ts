/**
 * PACK B — Cloud & enterprise software.
 *
 * Kestrel: a hyperscale cloud platform selling core infrastructure (Kestrel
 * Compute), an AI/ML service family (Kestrel Intelligence) and a data-residency
 * and sovereign-cloud line (Kestrel Sovereign) under one corporate parent.
 *
 * Why this vertical: performance and availability claims in enterprise
 * software are contractual rather than decorative, customer references carry
 * approval windows that genuinely lapse, and an availability incident is a
 * genuinely plausible crisis. Those three make the legal library, the graph
 * and the crisis flow do real work rather than decorate a screen.
 *
 * ---------------------------------------------------------------------------
 * RULES THIS FILE HOLDS ITSELF TO
 * ---------------------------------------------------------------------------
 *
 * 1. **Same shapes, same states as Pack A.** Every record is an unmodified
 *    type from `../../types`, every id uses the same prefix scheme, and the
 *    state-coverage checklist in the packs specification §4.3 is met item for
 *    item. A bug found in one pack is findable in all of them.
 *
 * 2. **Dates are offsets, never literals.** `d()` / `at()` below resolve
 *    against `PACK_ANCHOR`, which is the app's demo clock. Nothing in this
 *    file reads the wall clock, so the data is deterministic in CI and in the
 *    browser, and moving the anchor moves the whole world with it.
 *
 * 3. **Fictional brands, real regulators.** Kestrel, Kestrel Compute, Kestrel
 *    Intelligence and Kestrel Sovereign are invented, as is every customer,
 *    competitor and publication named here. ISO 27001, SOC 2, the Saudi PDPL,
 *    the EU AI Act and the CMA are real, and are named because that is what
 *    makes the governance content credible. No real company or product name
 *    appears anywhere in this pack.
 *
 * 4. **Market sizing is flagged, not asserted.** Every `MarketSizing` row
 *    carries the illustrative-placeholder caveat in its own `sourceLabel` and
 *    first assumption, so the caveat travels with the number onto the screen
 *    instead of living in a document nobody opens.
 *
 * 5. **Graph density.** Every asset except two deliberate exceptions is
 *    embedded in at least two content versions, and every content version is
 *    carried by at least one channel execution — so asset → version →
 *    execution → communication → activity → campaign is a real path for
 *    almost every record, not a lucky one.
 *
 *    The two exceptions are stated rather than hidden: `AST-016` is
 *    `Uploaded` and `AST-017` is `Rejected`. Referencing either from live
 *    content would make its status a lie, and an honest hole beats a
 *    convenient link.
 *
 * 6. **The showcase is wired, not narrated.** CRI-002 is an availability
 *    incident in EMEA; CMP-005 is the campaign whose entire thesis is
 *    zero-downtime compute. The campaign is `Paused`, its two sends are
 *    `Paused`, and the audit trail says which incident did it. The freeze is
 *    a fact in the data, not a caption on a screenshot.
 *
 * ---------------------------------------------------------------------------
 * WIRING
 * ---------------------------------------------------------------------------
 * This module exports collections and one assembled `cloudPack: SeedDB`.
 * It does NOT register itself — `src/data/seed/index.ts` owns pack selection.
 */

